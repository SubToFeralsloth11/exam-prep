// Builds Exam Quest so it opens by double-clicking (file://), where ES modules can't load.
//   js/template.js  - the PSMT Word template embedded as base64 (no fetch needed)
//   js/bundle.js    - every module bundled into one classic script, used by index.html
//   dist/ExamQuest.html - one self-contained file (CSS + JS inlined), used by HomeHub
// Run: bun tools/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const b64 = readFileSync(join(root, 'assets/psmt-final-template.docx')).toString('base64');
writeFileSync(join(root, 'js/template.js'), `// Generated by tools/build.mjs from assets/psmt-final-template.docx\nexport const TEMPLATE_B64 = '${b64}';\n`);

const out = await Bun.build({ entrypoints: [join(root, 'js/app.js')], format: 'iife', minify: true, target: 'browser' });
if (!out.success) { console.error(out.logs); process.exit(1); }
const js = await out.outputs[0].text();
writeFileSync(join(root, 'js/bundle.js'), js);

const css = readFileSync(join(root, 'css/styles.css'), 'utf8');
const html = readFileSync(join(root, 'index.html'), 'utf8')
  .replace(/<link rel="stylesheet" href="css\/styles.css">/, () => `<style>\n${css}\n</style>`)
  .replace(/<script src="js\/bundle.js"><\/script>/, () => `<script>\n${js.replace(/<\/script/gi, '<\\/script')}\n</script>`);
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/ExamQuest.html'), html);
console.log('built js/bundle.js and dist/ExamQuest.html');
